    assert.equal(await page.getByRole('textbox', { name: 'Admin label', exact: true }).inputValue(), 'Unsaved configuration');
    await page.getByRole('link', { name: 'Go to reports', exact: true }).click();
    await page.getByRole('button', { name: t.leave, exact: true }).click();
