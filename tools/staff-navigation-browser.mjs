    assert.equal(page.context().pages().length, 1);
    await page.locator('input[name=note]').fill('Follow up on this existing problem.');
    await page.locator('form:has(input[name=note]) button[type=submit]').click();
    await page.waitForFunction(() => window.followUpNote?.id === 'existing');
    await page.getByRole('link', { name: t.backToDraft, exact: true }).click();
    await page.locator('input[type=tel]').waitFor();
    await page.waitForTimeout(500);
    assert.equal(await page.locator('#title').inputValue(), 'Different customer problem');
    assert.equal(await page.locator('#description').inputValue(), 'Keep every detail while I inspect the previous ticket.');
    assert.equal(await page.locator('#targetDepartmentId').inputValue(), 'dept-1');
    assert.equal(await page.locator('#categoryId').inputValue(), 'category-1');
    assert.equal(await page.locator('input[type=tel]').inputValue(), '+962790000000');
    assert.equal(await page.locator('input[type=date]').inputValue(), '2026-12-01');
    assert.equal(await page.locator('#attachments').evaluate(input => input.files[0]?.name), 'proof.png');
    await page.getByRole('button', { name: phoneCopy.separate, exact: true }).click();
    await page.screenshot({ path: `${output}/${locale}-restored-draft.png`, fullPage: true });
    await page.getByRole('button', { name: 'Submit Ticket', exact: true }).click();
    await page.getByRole('heading', { name: 'Ticket queue', exact: true }).waitFor();
    assert.equal(await page.evaluate(() => window.createdTicket.customFields['customer-phone']), '+962790000000');
    assert.equal(await page.evaluate(() => window.createdTicket.attachments.length), 1);
    assert.deepEqual(await page.evaluate(() => window.createdTicket.acknowledgedPhoneFields), ['customer-phone']);
    assert.equal(await page.evaluate(() => Object.keys(sessionStorage).some(key => key.endsWith(':new-ticket'))), false);
    await page.getByRole('link', { name: 'Create another ticket', exact: true }).click();
    assert.equal(await page.locator('#title').inputValue(), '');
    await page.getByRole('link', { name: 'Reports', exact: true }).click();
    await page.locator('[data-view-ready="true"]').waitFor();
    await page.getByRole('textbox', { name: 'Report search', exact: true }).fill('customer status');
    await page.waitForFunction(() => JSON.parse(sessionStorage.getItem('cms:staff-work:staff-1:view:/reports:search') ?? '{}').value === 'customer status');
    await page.getByRole('link', { name: 'Review report ticket', exact: true }).click();
    const navigation = page.getByRole('navigation', { name: t.navigation, exact: true });
    await navigation.getByRole('button', { name: t.back, exact: true }).click();
    await page.getByRole('textbox', { name: 'Report search', exact: true }).waitFor();
    await page.waitForFunction(() => document.querySelector('[aria-label="Report search"]')?.value === 'customer status');
    assert.equal(await page.getByRole('textbox', { name: 'Report search', exact: true }).inputValue(), 'customer status');
    assert.equal(await page.locator('[data-staff-nav="/reports"]').getAttribute('aria-current'), 'page');
    await navigation.getByRole('button', { name: t.forward, exact: true }).click();
