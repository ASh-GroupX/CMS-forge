    await page.goto(`${base}/internal-tickets/new?locale=${locale}`);
    await page.locator('#title').fill('Private draft');
    await page.getByRole('button', { name: 'Log out', exact: true }).click();
    await page.getByRole('heading', { name: 'Signed out', exact: true }).waitFor();
    assert.equal(await page.evaluate(() => Object.keys(sessionStorage).some(key => key.startsWith('cms:staff-work:'))), false);
    await page.goto(`${base}/internal-tickets/new?locale=${locale}&owner=staff-2`);
    assert.equal(await page.locator('#title').inputValue(), '');
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2));
