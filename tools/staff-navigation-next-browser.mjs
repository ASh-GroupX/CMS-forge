import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { spawn } from 'node:child_process';
import { createServer } from 'node:net';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { chromium } from 'playwright-core';
import { navigationApiFixture } from './staff-navigation-api-fixture.mjs';
import { staffNavigationText } from '../apps/web/src/i18n/staff-navigation.ts';
import { ticketPhoneRuleText } from '../apps/web/src/i18n/staff-ticket-phone-rule.ts';
import { staffShellText } from '../apps/web/src/i18n/staff-shell.ts';

const webRequire = createRequire(new URL('../apps/web/package.json', import.meta.url));
const { server: api, state } = navigationApiFixture();
await new Promise(done => api.listen(0, '127.0.0.1', done));
const probe = createServer();
await new Promise(done => probe.listen(0, '127.0.0.1', done));
const port = probe.address().port;
await new Promise(done => probe.close(done));
const output = resolve('coverage/staff-navigation-next');
mkdirSync(output, { recursive: true });
let log = '';
const next = spawn(process.execPath, [webRequire.resolve('next/dist/bin/next'), 'start', '-p', String(port), '-H', '127.0.0.1'], {
  cwd: resolve('apps/web'), env: { ...process.env, API_URL: `http://127.0.0.1:${api.address().port}`, NODE_ENV: 'production' }, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true,
});
const base = `http://127.0.0.1:${port}`;
let browser;
try {
  await new Promise((done, reject) => {
    const timer = setTimeout(() => reject(new Error(`Next did not start: ${log}`)), 60000);
    const collect = chunk => { log += chunk; if (log.includes('Ready in')) { clearTimeout(timer); done(); } };
    next.stdout.on('data', collect); next.stderr.on('data', collect);
    next.once('exit', code => { clearTimeout(timer); reject(new Error(`Next exited ${code}: ${log}`)); });
  });
  browser = await chromium.launch({ headless: true });
  for (const locale of ['en', 'ar']) {
    const context = await browser.newContext({ viewport: { width: locale === 'en' ? 1440 : 390, height: 1000 } });
    await context.addCookies([{ name: 'cms_staff_session', value: 'navigation-test-session', url: base }]);
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const t = staffNavigationText[locale], phoneCopy = ticketPhoneRuleText[locale];
    await page.goto(`${base}/internal-tickets/new?locale=${locale}`);
    await page.waitForFunction(() => document.querySelector('form[data-draft-persisted]')?.dataset.draftPersisted === 'true');
    await page.locator('#title').fill('A separate customer problem');
    await page.locator('#description').fill('Do not lose these details when inspecting an existing ticket.');
    await page.locator('#targetDepartmentId').selectOption('dept-1');
    await page.locator('#categoryId').selectOption('category-1');
    await page.locator('input[type=tel]').fill('+962790000000');
    await page.getByRole('button', { name: 'Specific Date', exact: true }).click();
    await page.locator('input[type=date]').fill('2026-12-01');
    await page.locator('#attachments').setInputFiles({ name: 'proof.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Y9Z0S8AAAAASUVORK5CYII=', 'base64') });
    const duplicate = page.getByRole('link', { name: /TKT-100/ });
    await duplicate.waitFor();
    assert.equal(await duplicate.getAttribute('target'), null);
    await duplicate.click();
    await page.getByRole('heading', { name: 'Existing customer problem', exact: true }).waitFor();
    assert.equal(context.pages().length, 1);
    await page.waitForFunction(() => {
      const record = JSON.parse(sessionStorage.getItem('cms:staff-work:staff-1:navigation') ?? '{}').value;
      return record?.entries[record.index]?.id === history.state?.cmsStaffEntry?.id && record.entries[record.index].href === location.pathname + location.search;
    });
    await page.locator('input[name=note]').fill('Unsaved follow-up must survive native Back.');
    await page.getByRole('link', { name: t.backToDraft, exact: true }).click();
    await page.getByRole('dialog', { name: t.unsaved, exact: true }).waitFor();
    await page.getByRole('button', { name: t.stay, exact: true }).click();
    assert.equal(await page.locator('input[name=note]').inputValue(), 'Unsaved follow-up must survive native Back.');
    await page.evaluate(() => history.back());
    await page.waitForTimeout(250);
    await page.getByRole('dialog', { name: t.unsaved, exact: true }).waitFor();
    await page.getByRole('button', { name: t.stay, exact: true }).click();
    assert.equal(await page.locator('input[name=note]').inputValue(), 'Unsaved follow-up must survive native Back.');
    assert.ok(page.url().includes('/internal-tickets/existing'));
    await page.evaluate(() => history.back());
    await page.getByRole('dialog', { name: t.unsaved, exact: true }).waitFor();
    await page.getByRole('button', { name: t.leave, exact: true }).click();
    await page.locator('#title').waitFor();
    assert.equal(await page.locator('#title').inputValue(), 'A separate customer problem');
    await page.getByRole('navigation', { name: t.navigation, exact: true }).getByRole('button', { name: t.forward, exact: true }).click();
    await page.locator('input[name=note]').waitFor();
    await page.locator('input[name=note]').fill('Unsaved follow-up must survive native Back.');
    await page.locator('form:has(input[name=note]) button[type=submit]').click();
    await page.getByText('Unsaved follow-up must survive native Back.', { exact: true }).waitFor();
    await page.getByRole('link', { name: t.backToDraft, exact: true }).click();
    await page.locator('input[type=tel]').waitFor();
    await page.waitForTimeout(500);
    assert.equal(await page.locator('#title').inputValue(), 'A separate customer problem');
    assert.equal(await page.locator('#description').inputValue(), 'Do not lose these details when inspecting an existing ticket.');
    assert.equal(await page.locator('#targetDepartmentId').inputValue(), 'dept-1');
    assert.equal(await page.locator('#categoryId').inputValue(), 'category-1');
    assert.equal(await page.locator('input[type=tel]').inputValue(), '+962790000000');
    assert.equal(await page.locator('input[type=date]').inputValue(), '2026-12-01');
    assert.equal(await page.locator('#attachments').evaluate(input => input.files[0]?.name), 'proof.png');
    await page.getByRole('button', { name: phoneCopy.separate, exact: true }).click();
    await page.screenshot({ path: `${output}/${locale}-restored.png`, fullPage: true });
    await page.getByRole('button', { name: 'Submit Ticket', exact: true }).click();
    await page.waitForURL(url => url.pathname === '/internal-tickets');
    assert.equal(state.created.title, 'A separate customer problem');
    assert.equal(state.created.customFields['customer-phone'], '+962790000000');
    assert.deepEqual(state.created.acknowledgedPhoneFields, ['customer-phone']);
    assert.equal(await page.evaluate(() => Object.keys(sessionStorage).some(key => key.endsWith(':new-ticket'))), false);
    const navigation = page.getByRole('navigation', { name: t.navigation, exact: true });
    await navigation.getByRole('button', { name: t.back, exact: true }).click();
    await page.locator('#title').waitFor();
    assert.equal(await page.locator('#title').inputValue(), '');
    await page.locator('#categoryId').selectOption('category-1');
    await page.getByRole('button', { name: 'High', exact: true }).click();
    await page.getByRole('button', { name: 'Specific Date', exact: true }).click();
    await page.locator('input[type=date]').fill('2026-12-15');
    await page.getByRole('link', { name: locale === 'ar' ? 'القسم' : 'Department', exact: true }).click();
    await page.waitForURL(url => url.pathname === '/internal-tickets');
    await navigation.getByRole('button', { name: t.back, exact: true }).click();
    await page.locator('input[type=date]').waitFor();
    assert.equal(await page.locator('#categoryId').inputValue(), 'category-1');
    assert.equal(await page.locator('input[type=date]').inputValue(), '2026-12-15');
    assert.equal(await page.getByRole('button', { name: 'High', exact: true }).getAttribute('aria-pressed'), 'true');
    await page.getByRole('button', { name: t.discard, exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: t.discard, exact: true }).click();
    assert.equal(await page.locator('#categoryId').inputValue(), '');
    await page.locator('#title').fill('Private draft before logout');
    if (locale === 'ar') await page.getByRole('button', { name: staffShellText[locale].mobileNav.more, exact: true }).click();
    await page.getByRole('button', { name: staffShellText[locale].auth.logout, exact: true }).click();
    await page.waitForURL(url => url.pathname === '/');
    assert.equal(await page.evaluate(() => Object.keys(sessionStorage).some(key => key.startsWith('cms:staff-work:'))), false);
    assert.deepEqual(errors, []);
    await context.close();
  }
  console.log('Real production Next browser proof passed EN/AR: same-tab review, native Back note guard, notes save, field/file restore, create, metadata-only draft, discard and desktop/mobile logout. Backend API uses controlled fixtures.');
} finally {
  writeFileSync(`${output}/next.log`, log);
  if (browser) await browser.close();
  next.kill();
  await new Promise(done => api.close(done));
}
